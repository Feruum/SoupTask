import { expect, test } from '@playwright/test'

test('a pinned original row keeps exact values after the cursor moves and opens its revision', async ({ page }) => {
  await page.goto('/runs/kazakh-sft-005')
  const plot = page.getByTestId('loss-chart')
  await expect(plot).toHaveAttribute('data-view-ready', 'true')
  await page.getByLabel('From step', { exact: true }).fill('500000')
  await page.getByLabel('To step', { exact: true }).fill('500002')
  await page.getByRole('button', { name: 'Apply range', exact: true }).click()
  await expect(plot).toHaveAttribute('data-range-min', '500000')
  await plot.locator('.u-over').scrollIntoViewIfNeeded()
  const box = await plot.locator('.u-over').boundingBox()
  if (!box) throw new Error('Missing physical plot')
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
  await page.getByRole('button', { name: 'Pin row 500001', exact: true }).first().click()
  const pinned = page.getByRole('region', { name: 'Pinned source row', exact: true })
  await expect(pinned.getByTestId('pinned-loss')).toHaveText('100')
  await plot.locator('.u-over').scrollIntoViewIfNeeded()
  const nextBox = await plot.locator('.u-over').boundingBox()
  if (!nextBox) throw new Error('Missing physical plot after pin')
  await page.mouse.move(nextBox.x + nextBox.width * .1, nextBox.y + nextBox.height / 2)
  await expect(pinned.getByTestId('pinned-loss')).toHaveText('100')
  await expect(pinned.getByRole('link', { name: 'Open exact source row' })).toHaveAttribute('href', /sourceIndex=500001&revision=/)
  await pinned.getByRole('link', { name: 'Open exact source row' }).click()
  await expect(page.getByTestId('inspected-loss')).toHaveText('100.000')
})
