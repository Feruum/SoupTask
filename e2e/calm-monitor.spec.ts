for (const theme of ['dark', 'light'] as const) for (const width of [320, 390, 768, 1440]) {
  test(`${theme} ${width}px monitor fits and stays accessible`, async ({ page }, info) => {
    await page.setViewportSize({ width, height: width < 800 ? 844 : 1000 })
    await page.emulateMedia({ reducedMotion: 'reduce' })
    await page.addInitScript(value => localStorage.setItem('soup-theme', value), theme)
    await page.goto('/dashboard')
    await expect(page.getByTestId('loss-chart')).toHaveAttribute('data-view-ready', 'true')
    await expect(page.locator('.calm-selected-header .calm-snapshot')).toContainText('Demo snapshot · Not live')
    if (width === 320) {
      const rows = page.locator('.calm-facts > div').filter({ has: page.locator('dt', { hasText: 'Raw rows' }) }).locator('dd')
      expect(await rows.evaluate(element => {
        const range = document.createRange()
        range.selectNodeContents(element)
        return range.getClientRects().length
      })).toBe(1)
      expect(await rows.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
      await page.locator('.calm-step-inspection > summary').click()
      const stepInput = page.getByRole('spinbutton', { name: 'Recorded step', exact: true })
      expect((await stepInput.boundingBox())!.height).toBeGreaterThanOrEqual(44)
      expect(await stepInput.evaluate(element => Number.parseFloat(getComputedStyle(element).fontSize))).toBeGreaterThanOrEqual(16)
    }
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    if (width < 1000) {
      await expect(page.locator('.calm-navigator')).not.toHaveAttribute('open', '')
      const run = await page.getByTestId('selected-experiment').boundingBox()
      expect(run!.y).toBeLessThan(360)
    }
    const audit = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa']).analyze()
    expect(audit.violations).toEqual([])
    await page.screenshot({ path: `reports/calm-monitor/${theme}-${width}.png`, fullPage: true })
    await info.attach('axe', { body: JSON.stringify(audit.violations), contentType: 'application/json' })
  })
}

test('phone run switching collapses the chooser and the chart remains touch scrollable', async ({ browser }) => {
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true })
  const page = await context.newPage()
  await page.goto('/dashboard')
  await page.locator('.calm-navigator > summary').tap()
  await page.getByRole('combobox', { name: 'Selected experiment', exact: true }).selectOption('kazakh-sft-006')
  await expect(page.locator('.calm-navigator')).not.toHaveAttribute('open', '')
  await expect(page.getByTestId('selected-experiment')).toContainText('kazakh-sft-006')
  const plot = page.getByTestId('loss-chart')
  await expect(plot).toHaveAttribute('data-view-ready', 'true')
  await plot.locator('.u-over').tap()
  await expect(page.locator('.chart-hover-value').first()).toBeVisible()
  const box = await plot.locator('.u-over').boundingBox()
  const before = await page.evaluate(() => scrollY)
  const cdp = await context.newCDPSession(page)
  const x = box!.x + 20, y = box!.y + box!.height - 24
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x, y }] })
  for (let offset = 20; offset <= 140; offset += 20) await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x, y: y - offset }] })
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
  await expect.poll(() => page.evaluate(() => scrollY)).toBeGreaterThan(before + 40)
  await cdp.detach()
  await context.close()
})
